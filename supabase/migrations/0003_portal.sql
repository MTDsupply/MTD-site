-- Customer portal: order numbers and fulfilment fields, business profiles,
-- "your usual" standing lists, default addresses.

-- Orders: a short human number, plus shipping fields the team fills in from the
-- Supabase dashboard once a parcel leaves. Shown on the site only when set.
alter table public.orders
  add column if not exists number bigint generated by default as identity (start with 1001),
  add column if not exists shipped_at timestamptz,
  add column if not exists carrier text,
  add column if not exists tracking_number text,
  add column if not exists tracking_url text;
create unique index if not exists orders_number_idx on public.orders (number);

-- Business profile, one per signed-in user.
create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  company text not null default '',
  contact_name text not null default '',
  phone text,
  business_type text,
  delivery_notes text,
  updated_at timestamptz not null default now()
);
alter table public.profiles enable row level security;
drop policy if exists "own profile select" on public.profiles;
create policy "own profile select" on public.profiles for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "own profile insert" on public.profiles;
create policy "own profile insert" on public.profiles for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "own profile update" on public.profiles;
create policy "own profile update" on public.profiles for update to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
grant select, insert, update on public.profiles to authenticated;

-- "Your usual": the lines a café or hotel reorders, editable, one click to cart.
create table if not exists public.usual_items (
  user_id uuid not null references auth.users(id) on delete cascade,
  sku text not null,
  unit text not null,
  qty int not null check (qty > 0 and qty <= 500),
  updated_at timestamptz not null default now(),
  primary key (user_id, sku, unit)
);
alter table public.usual_items enable row level security;
drop policy if exists "own usual select" on public.usual_items;
create policy "own usual select" on public.usual_items for select to authenticated using ((select auth.uid()) = user_id);
drop policy if exists "own usual insert" on public.usual_items;
create policy "own usual insert" on public.usual_items for insert to authenticated with check ((select auth.uid()) = user_id);
drop policy if exists "own usual update" on public.usual_items;
create policy "own usual update" on public.usual_items for update to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
drop policy if exists "own usual delete" on public.usual_items;
create policy "own usual delete" on public.usual_items for delete to authenticated using ((select auth.uid()) = user_id);
grant select, insert, update, delete on public.usual_items to authenticated;

-- Addresses: a default, a country and delivery notes.
alter table public.addresses
  add column if not exists is_default boolean not null default false,
  add column if not exists country text not null default 'CA',
  add column if not exists notes text;
drop policy if exists "own addresses update" on public.addresses;
create policy "own addresses update" on public.addresses for update to authenticated
  using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
grant update on public.addresses to authenticated;
